export type FaceStage = { id: string; raw: string }
export type EnemyKind = 'cute' | 'horror'
export type Enemy = { id: string; kind: EnemyKind; stages: FaceStage[] }

// 段階名（昇順）。全種で共通。段階を増やすときはここと各種の素材を足す
export const STAGE_IDS = ['25', '50', '75', '100', '150', '200', '300']

const build = (id: string, kind: EnemyKind, raws: string[]): Enemy => {
  if (raws.length !== STAGE_IDS.length) throw new Error(`enemy ${id}: stage count ${raws.length} != ${STAGE_IDS.length}`)
  return { id, kind, stages: STAGE_IDS.map((sid, i) => ({ id: sid, raw: raws[i] })) }
}

// 種類を足すときは配列に1要素を追加するだけ。index 0-5 が horror、6-12 が cute（並びは慣習で、コードは kind から導出する）
export const ENEMIES: Enemy[] = [
  build('businessman', 'horror', [bm25, bm50, bm75, bm100, bm150, bm200, bm300]),
  build('killer', 'horror', [k25, k50, k75, k100, k150, k200, k300]),
  build('woman', 'horror', [w25, w50, w75, w100, w150, w200, w300]),
  build('visitor', 'horror', [v25, v50, v75, v100, v150, v200, v300]),
  build('brokeneyes', 'horror', [be25, be50, be75, be100, be150, be200, be300]),
  build('smile', 'horror', [s25, s50, s75, s100, s150, s200, s300]),
  build('chocolate', 'cute', [ch25, ch50, ch75, ch100, ch150, ch200, ch300]),
  build('crab', 'cute', [cr25, cr50, cr75, cr100, cr150, cr200, cr300]),
  build('dount', 'cute', [d25, d50, d75, d100, d150, d200, d300]),
  build('goya', 'cute', [g25, g50, g75, g100, g150, g200, g300]),
  build('lemon', 'cute', [l25, l50, l75, l100, l150, l200, l300]),
  build('mail', 'cute', [m25, m50, m75, m100, m150, m200, m300]),
  build('paper', 'cute', [p25, p50, p75, p100, p150, p200, p300]),
]

// kind ごとの ENEMIES の index 群（並び順に依存しない）
export const indicesOf = (kind: EnemyKind): number[] =>
  ENEMIES.flatMap((e, i) => (e.kind === kind ? [i] : []))
